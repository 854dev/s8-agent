import test from 'node:test';
import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { copyFile, mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
const execute = promisify(execFile);

test('explicit job conversion requires a capable daemon and preserves expiry, activation, other jobs and rollback script', async t => {
  const agent = await mkdtemp(path.join(os.tmpdir(), 's8-job-conversion-'));
  t.after(() => rm(agent, { recursive: true, force: true }));
  await mkdir(path.join(agent, 'pi/bin'), { recursive: true });
  await mkdir(path.join(agent, 'pi/lib'));
  await copyFile(new URL('../bin/projectman-job.mjs', import.meta.url), path.join(agent, 'pi/bin/projectman-job.mjs'));
  await copyFile(new URL('../lib/projectman-client.ts', import.meta.url), path.join(agent, 'pi/lib/projectman-client.ts'));
  await copyFile(new URL('../lib/projectman-preflight.mjs', import.meta.url), path.join(agent, 'pi/lib/projectman-preflight.mjs'));
  await copyFile(new URL('../lib/scheduler-store.mjs', import.meta.url), path.join(agent, 'pi/lib/scheduler-store.mjs'));
  await writeFile(path.join(agent, 'pi/lib/telegram-config.mjs'), `export const agentRoot = ${JSON.stringify(agent)};`);
  let writes = 0;
  const server = createServer((req, res) => {
    if (req.method !== 'GET') { writes++; res.writeHead(400).end(); return; }
    assert.equal(req.headers.authorization, 'Bearer fixture-token');
    res.setHeader('content-type', 'application/json');
    res.end(JSON.stringify({ content: [{ uid: 'cnt_project', type: 'project' }], last: true }));
  });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise(resolve => server.close(resolve)));
  const root = path.join(agent, '.s8-runtime/scheduler');
  await mkdir(path.join(root, 'scripts'), { recursive: true });
  const expiry = '2099-01-01T00:00:00Z';
  const other = { id: 'other', time: '09:00', enabled: true, timezone: 'Asia/Seoul' };
  await writeFile(path.join(root, 'jobs.json'), JSON.stringify({ version: 1, jobs: [{ id: 'count', intervalMinutes: 30, enabled: false, timezone: 'Asia/Seoul', expiresAt: expiry, note: 'preserve' }, other] }));
  await writeFile(path.join(root, 'scripts/count.sh'), 'echo legacy');
  const cli = path.join(agent, 'pi/bin/projectman-job.mjs');
  const env = { PHCMS_API_URL: `http://127.0.0.1:${server.address().port}/api/v2`, PHCMS_ACCESS_TOKEN: 'fixture-token' };
  await writeFile(path.join(root, 'owner.lock'), `${process.pid}\nexpiresAt-v1\n`);
  await assert.rejects(execute(process.execPath, [cli, 'count', 'cnt_project'], { env }), /conversion failed/);
  assert.equal(JSON.parse(await readFile(path.join(root, 'jobs.json'), 'utf8')).jobs[0].kind, undefined);
  await writeFile(path.join(root, 'owner.lock'), `${process.pid}\nexpiresAt-v1\nprojectman-v1\n`);
  const result = await execute(process.execPath, [cli, 'count', 'cnt_project'], { env });
  assert.equal(result.stdout.includes('fixture-token'), false);
  const stored = JSON.parse(await readFile(path.join(root, 'jobs.json'), 'utf8')).jobs;
  assert.equal(stored[0].kind, 'projectman');
  assert.equal(stored[0].projectUid, 'cnt_project');
  assert.equal(stored[0].intervalMinutes, 5);
  assert.equal(stored[0].expiresAt, expiry);
  assert.equal(stored[0].enabled, false);
  assert.equal(stored[0].note, 'preserve');
  assert.deepEqual(stored[1], other);
  assert.equal(await readFile(path.join(root, 'scripts/count.sh'), 'utf8'), 'echo legacy');
  assert.equal(writes, 0);
});
